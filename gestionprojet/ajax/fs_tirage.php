define('AJAX_SCRIPT', true);

require_once(__DIR__ . '/../../../config.php');
require_once(__DIR__ . '/../lib.php');

$id = required_param('id', PARAM_INT); // CM ID.
$copyid = required_param('copyid', PARAM_INT);
$action = required_param('action', PARAM_ALPHA);

$cm = get_coursemodule_from_id('gestionprojet', $id, 0, false, MUST_EXIST);
$course = $DB->get_record('course', ['id' => $cm->course], '*', MUST_EXIST);
$gestionprojet = $DB->get_record('gestionprojet', ['id' => $cm->instance], '*', MUST_EXIST);

require_login($course, true, $cm);
require_sesskey();
$context = context_module::instance($cm->id);
require_capability('mod/gestionprojet:configureteacherpages', $context);

header('Content-Type: application/json');
echo json_encode(['success' => true, 'fs' => gestionprojet_fs_tirage_action($gestionprojet, $copyid, $action)]);
